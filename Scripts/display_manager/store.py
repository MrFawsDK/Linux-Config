# =============================================================================
# store.py - Saving the layout to ~/.config/hypr/monitors.lua
# =============================================================================
# hyprctl eval only changes the running session. To survive a reboot or a
# config reload, the confirmed layout is written as plain hl.monitor{...}
# calls to monitors.lua, and hyprland.lua loads that file right after its
# catch-all monitor rule:
#
#     local ok, err = pcall(dofile, os.getenv("HOME") .. "/.config/hypr/monitors.lua")
#
# The app only ever writes this one generated file. It never edits
# hyprland.lua itself; is_hooked() just checks that the line is there so the
# window can warn if saving would have no effect.
#
# Choices that matter:
#   * External monitors are saved as `desc:<description>` when the
#     description is unique, so the settings follow the monitor to another
#     port or dock. Built-in panels and duplicates use the connector name.
#   * Disabled monitors are NOT saved. A saved "disabled" rule for the laptop
#     panel would boot to a black screen the first time no external monitor
#     is attached. Turning a display off is therefore session-only.
#   * The file is validated with `luac -p` (if installed) and written
#     atomically (temp file + rename), so Hyprland never reads half a file.
# =============================================================================

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

from .hypr import Monitor, Settings, monitor_lua

HYPR_DIR = Path.home() / ".config" / "hypr"
MONITORS_FILE = HYPR_DIR / "monitors.lua"
HYPRLAND_FILE = HYPR_DIR / "hyprland.lua"


class StoreError(Exception):
    pass


def is_hooked() -> bool:
    try:
        return "monitors.lua" in HYPRLAND_FILE.read_text()
    except OSError:
        return False


def selector(monitor: Monitor, monitors: list[Monitor]) -> str:
    if monitor.internal or not monitor.description:
        return monitor.name
    duplicates = sum(1 for m in monitors if m.description == monitor.description)
    return monitor.name if duplicates > 1 else f"desc:{monitor.description}"


def render(monitors: list[Monitor], settings: dict[str, Settings]) -> str:
    lines = [
        "-- =====================================================================",
        "-- monitors.lua - generated by MrFaws Display Manager (`screen`)",
        f"-- Saved {time.strftime('%Y-%m-%d %H:%M')}. Changes made here by hand are",
        "-- overwritten the next time you press Apply -> Keep in the app.",
        "-- Loaded from hyprland.lua; delete this file to go back to auto setup.",
        "-- =====================================================================",
        "",
    ]
    for monitor in monitors:
        s = settings.get(monitor.name)
        if s is None or not s.enabled:
            continue  # see header: off is session-only
        comment = f"-- {monitor.name}: {monitor.description}"
        lines.append(" ".join(comment.splitlines()))  # EDID text: keep it on one line
        lines.append(monitor_lua(selector(monitor, monitors), s))
    return "\n".join(lines) + "\n"


def save(monitors: list[Monitor], settings: dict[str, Settings]) -> Path:
    text = render(monitors, settings)
    HYPR_DIR.mkdir(parents=True, exist_ok=True)

    fd, tmp = tempfile.mkstemp(prefix=".monitors.", suffix=".lua", dir=HYPR_DIR)
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        os.chmod(tmp, 0o644)
        if shutil.which("luac"):
            check = subprocess.run(["luac", "-p", tmp], capture_output=True, text=True)
            if check.returncode != 0:
                raise StoreError(f"Generated Lua is invalid: {check.stderr.strip()}")
        if MONITORS_FILE.exists():
            shutil.copy2(MONITORS_FILE, MONITORS_FILE.with_suffix(".lua.bak"))
        os.replace(tmp, MONITORS_FILE)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return MONITORS_FILE
